// Language context
let currentLang = localStorage.getItem('crm-lang') || 'en';

export function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('crm-lang', lang);
  window.dispatchEvent(new CustomEvent('language-change', { detail: { lang } }));
}

export function getLanguage() {
  return currentLang;
}

// Pure translation function (no React hooks)
export function t(key, params = {}) {
  const langData = translations[currentLang] || translations.en;
  let text = langData[key] || translations.en[key] || key;
  
  Object.keys(params).forEach(paramKey => {
    text = text.replace(`{${paramKey}}`, params[paramKey]);
  });
  
  return text;
}

// React hook for components that need reactive translations
export function useTranslation() {
  const [lang, setLangState] = React.useState(currentLang);
  
  React.useEffect(() => {
    const handler = (e) => {
      setLangState(e.detail.lang);
      currentLang = e.detail.lang;
    };
    window.addEventListener('language-change', handler);
    return () => window.removeEventListener('language-change', handler);
  }, []);
  
  return {
    t: (key, params) => {
      const langData = translations[lang] || translations.en;
      return langData[key] || translations.en[key] || key;
    },
    lang,
    setLang: (newLang) => {
      setLanguage(newLang);
      setLangState(newLang);
    }
  };
}
